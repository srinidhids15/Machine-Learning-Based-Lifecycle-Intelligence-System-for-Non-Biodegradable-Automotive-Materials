"""
Physics-grounded lifecycle data simulator for non-biodegradable automotive
materials.

Design intent
-------------
The dataset originally used in this project assigned labels almost independently
of its features, which capped every model near the majority-class baseline. This
simulator replaces that with a generator built on three principles:

1. REAL PHYSICAL ANCHORS. Every material property comes from the published
   reference table in `material_properties.py` (Ashby, GREET 2023, EU ELV
   Directive). Part mass follows from density and component geometry, embodied
   energy and CO2 follow from mass, so features are physically CORRELATED rather
   than independently random.

2. AN EXPLICIT DEGRADATION MODEL. A part's condition is not drawn at random. It
   is integrated from the thermal, photo-oxidative and corrosive dose the part
   accumulates over its service life, modulated by the duty cycle of its
   component and vehicle type. This is what makes service age and odometer
   genuinely predictive, as they are in real end-of-life data.

3. A DOCUMENTED, PARTIALLY OBSERVED DECISION RULE. Labels come from a
   multi-criteria (MCDA) scoring function over latent lifecycle state, following
   the ISO 14040 impact-accounting structure. Crucially, several rule inputs are
   deliberately WITHHELD from the exported feature set, and those that remain are
   exported only as noisy or coarsened observations:

       latent                        exported as
       ---------------------------   ------------------------------------------
       degradation_index (float)     4-level 'Material Condition' + a tensile
                                     strength measurement carrying 8% NDT noise
       contamination_level (float)   binary 'Fluid Contamination' flag, plus
                                     'Recyclate Value ($)' at 15% market noise
       separability (float)          not exported; 'Joining Method' and
                                     'Coating Present' hint at it, and
                                     'Dismantling Cost ($)' reflects it through
                                     18% labour-rate scatter
       hazard_score (float)          3-level 'Hazardous Level' band only
       MCDA scores + Gumbel noise    not exported at all

   This matters methodologically. Because the model never sees the latent state
   or the scores, it cannot invert the rule; it has to learn a SURROGATE of the
   LCA decision model from partial, noisy observations. That keeps the learning
   problem genuine and bounds achievable accuracy well below 100%. The residual
   irreducible error is reported by `estimate_bayes_ceiling`.

Honest limitation
-----------------
Labels are generated by a rule, not observed from dismantling plants. The models
therefore learn that rule, and reported accuracy measures surrogate fidelity,
not real-world disposition accuracy. The rule's weights and thresholds are
derived from published recycling economics and ELV policy so that it encodes
domain knowledge rather than arbitrary choices, and `train.py` additionally
evaluates on held-out MATERIALS and COMPONENTS never seen in training, which
tests genuine generalisation instead of memorisation.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from . import material_properties as mp

RNG_SEED = 42

# Monte Carlo draws used to marginalise the unobserved shocks per part.
_MC_DRAWS = 400

DISPOSITIONS = ["Reuse", "Recycle", "Dispose"]
RISK_TIERS = ["Low", "Moderate", "High", "Critical"]

# ELV Annex II restricted heavy-metal stabilisers were phased out from July 2003,
# so parts manufactured before then may carry legacy Pb/Cd/Cr-VI additives.
ELV_ANNEX_II_CUTOFF_YEAR = 2003

# Selection temperature for the stochastic label draw. Higher values mean the
# MCDA scores dominate; lower values mean more genuine ambiguity between
# near-tied options. 5.5 was selected by scanning this parameter against
# `estimate_bayes_ceiling`: it leaves roughly 7% irreducible label error, which
# is the order of inter-assessor disagreement reported for manual end-of-life
# triage decisions. Lower values make the task needlessly unlearnable; much
# higher values make the rule near-deterministic and the problem trivial.
LABEL_TEMPERATURE = 5.5

# Unobserved heterogeneity: the standard deviation of per-part utility shocks
# that are NEVER exported as features.
#
# This is the methodological core of the generator. The latent lifecycle state
# (degradation, contamination, separability, hazard) is largely RECOVERABLE from
# the exported features, and correctly so - separability really is determined by
# which component, joining method and coating a part has. If those were the only
# hidden quantities, a model could in principle reconstruct the whole rule, and
# the learning task would collapse into algebra.
#
# Real end-of-life decisions, though, also turn on factors that appear in no
# dismantling database:
#   * hidden internal damage - delamination, fatigue cracking and internal
#     corrosion that neither a surface inspection nor a tensile test reveals,
#   * local recyclate market conditions - demand and gate prices at the specific
#     plant on the specific day,
#   * operator and plant capability - assessor judgement and which separation
#     equipment that facility actually has.
#
# Reuse carries the largest shock because hidden internal condition is the
# dominant unknown when judging whether a part can be put back into service.
# These shocks are what make the problem genuinely statistical rather than
# algebraic, and they set the real ceiling for any feature-based model
# (see `estimate_feature_ceiling`).
UNOBSERVED_SIGMA = np.array([0.30, 0.20, 0.20])  # Reuse, Recycle, Dispose

# Calibration offsets added to the raw MCDA utilities before the label draw.
# The raw weights express the RELATIVE desirability of each route, but they do
# not by themselves reproduce the observed composition of real end-of-life
# vehicle streams. The EU ELV Directive 2000/53/EC Art. 7(2) target, and the
# Eurostat ELV treatment statistics reported against it, put roughly 85% of ELV
# mass into reuse plus recycling, with disposal the minority route. These
# offsets shift the generator onto that published composition; they are fitted
# once by `calibrate_bias` and then held fixed.
DISPOSITION_BIAS = np.array([0.2109, 0.5034, -0.7143])


# ---------------------------------------------------------------------------
# Degradation physics
# ---------------------------------------------------------------------------
def _degradation_index(mat, comp, duty, service_years, odometer_km, rng):
    """
    Integrate accumulated damage into a 0-1 degradation index.

    Each degradation mechanism contributes a rate equal to the material's
    susceptibility times the exposure severity the component imposes. Damage
    accumulates with an exponential-saturation law, the standard first-order
    form for ageing processes, so a part cannot degrade past total failure.
    """
    thermal_rate = mat["thermal_degradation"] * comp["thermal_load"] * duty["thermal_bias"]
    uv_rate = mat["uv_degradation"] * comp["uv_load"]
    corrosion_rate = mat["corrosion_suscept"] * comp["corrosive_load"]

    combined_rate = 0.45 * thermal_rate + 0.30 * uv_rate + 0.25 * corrosion_rate

    # Mileage intensity: a part on a hard-driven vehicle ages faster than the
    # calendar alone implies. Square root keeps the effect sub-linear.
    expected_km = max(duty["annual_km"] * service_years, 1.0)
    intensity = np.sqrt(odometer_km / expected_km)

    equivalent_years = service_years * np.clip(intensity, 0.4, 2.2)

    # Unit-to-unit scatter in ageing: manufacturing variation and how the
    # individual vehicle was stored and maintained.
    scatter = rng.lognormal(mean=0.0, sigma=0.28)

    dose = 1.30 * combined_rate * (equivalent_years / 10.0) * scatter
    return float(np.clip(1.0 - np.exp(-dose), 0.0, 0.985))


def _condition_label(degradation_index):
    """Coarsen the latent degradation index into the 4 grades a dismantler records."""
    if degradation_index < 0.18:
        return "Excellent"
    if degradation_index < 0.38:
        return "Good"
    if degradation_index < 0.62:
        return "Fair"
    return "Poor"


def _separability(comp, joining_method, coating_present):
    """
    Latent 0-1 ease of separating this part into a clean single-material stream.
    Not exported: the model sees only joining method and coating presence.
    """
    joint_penalty = {"Clip-fit": 0.00, "Bolted": 0.08, "Welded": 0.30,
                     "Adhesive-bonded": 0.45, "Over-moulded": 0.55}[joining_method]
    value = comp["dismantling_ease"] * (1.0 - joint_penalty)
    if coating_present:
        value *= 0.70  # paint, chrome and flock all contaminate the recyclate
    return float(np.clip(value, 0.02, 1.0))


# ---------------------------------------------------------------------------
# MCDA decision rule
# ---------------------------------------------------------------------------
def _mcda_scores(mat, comp, state):
    """
    Score the three dispositions from latent lifecycle state.

    Weights encode published end-of-life logic:
      - Reuse requires retained mechanical function and clean, easy removal,
        and is heavily restricted for safety-critical parts (type-approval
        rules bar the resale of structural and restraint components).
      - Recycling requires an established reprocessing route, economic
        recyclate value, and a separable, uncontaminated stream.
      - Disposal is driven by hazard content, contamination, irreversible
        crosslinking, and absent recovery value.
    """
    strength_retention = state["strength_retention"]
    degradation = state["degradation_index"]
    contamination = state["contamination_level"]
    separability = state["separability"]
    hazard = state["hazard_score"]

    # --- Reuse -------------------------------------------------------------
    reuse = (
        1.35 * strength_retention
        + 0.80 * (1.0 - degradation)
        + 0.55 * separability
        + 0.45 * (1.0 - contamination)
        - 0.70 * hazard
    )
    if comp["safety_critical"]:
        # A safety-critical part is only reusable if near-pristine.
        reuse -= 1.25
        if degradation > 0.25:
            reuse -= 1.40
    if not mat["reprocessable"] and strength_retention > 0.75:
        # Thermosets and composites cannot be remelted, which makes direct
        # reuse their single best recovery route while still strong.
        reuse += 0.55

    # --- Recycle -----------------------------------------------------------
    value_density = np.log1p(mat["recyclate_value"]) / np.log1p(6.0)  # 0-1 scaled
    recycle = (
        1.50 * mat["recycle_fraction"]
        + 0.95 * value_density
        + 0.70 * separability
        + 0.60 * (1.0 - contamination)
        - 0.85 * hazard
        + 0.40 * (1.0 - degradation)
    )
    if not mat["reprocessable"]:
        recycle -= 1.05
    if state["coating_present"] and mat["family"] in ("Thermoplastic", "Thermoset"):
        recycle -= 0.45

    # --- Dispose -----------------------------------------------------------
    dispose = (
        1.40 * hazard
        + 1.00 * contamination
        + 0.85 * degradation
        + 0.75 * (1.0 - mat["recycle_fraction"])
        - 0.60 * value_density
        + 0.50 * (1.0 - separability)
    )
    if not mat["reprocessable"]:
        dispose += 0.35

    return np.array([reuse, recycle, dispose], dtype=float)


def _environmental_risk(mat, state, mass_kg, rng):
    """
    Second target required by the synopsis: the environmental risk the part
    poses if it is mishandled at end-of-life.

    Combines intrinsic hazard, landfill persistence (inverse of the established
    recycling route), the mass of material at stake, and the embodied carbon
    that is lost if the part is landfilled rather than recovered.
    """
    mass_norm = np.clip(np.log1p(mass_kg) / np.log1p(60.0), 0.0, 1.0)
    gwp_norm = np.clip(mat["gwp_kg_co2e_per_kg"] / 24.0, 0.0, 1.0)

    score = (
        0.38 * state["hazard_score"]
        + 0.24 * (1.0 - mat["recycle_fraction"])
        + 0.18 * mass_norm
        + 0.20 * gwp_norm
    )
    if state["contamination_level"] > 0.5:
        score += 0.08  # fouled parts leach into soil and groundwater faster
    if state["legacy_additive"]:
        score += 0.07  # ELV Annex II heavy metals

    score += rng.normal(0.0, 0.035)  # assessor variability

    if score < 0.28:
        return "Low", score
    if score < 0.45:
        return "Moderate", score
    if score < 0.62:
        return "High", score
    return "Critical", score


# ---------------------------------------------------------------------------
# Generator
# ---------------------------------------------------------------------------
def generate(n_samples=6000, seed=RNG_SEED, reference_year=2026,
             include_latents=False):
    """
    Generate a physically consistent automotive material lifecycle dataset.

    Parameters
    ----------
    n_samples : int
        Number of end-of-life parts to simulate.
    seed : int
        Random seed, for reproducibility.
    reference_year : int
        The year the end-of-life assessment is performed.
    include_latents : bool
        If True, also return the hidden rule inputs. Use this ONLY for
        diagnostics such as the Bayes-ceiling estimate; never for training,
        since it would make the label trivially recoverable.
    """
    rng = np.random.default_rng(seed)
    components = list(mp.COMPONENTS.keys())
    rows = []

    for _ in range(n_samples):
        comp_name = components[rng.integers(len(components))]
        comp = mp.COMPONENTS[comp_name]

        choices = mp.COMPONENT_MATERIALS[comp_name]
        mat_name = mp.resolve(choices[rng.integers(len(choices))])
        mat = mp.MATERIALS[mat_name]

        veh_type = mp.VEHICLE_TYPES[rng.integers(len(mp.VEHICLE_TYPES))]
        duty = mp.VEHICLE_DUTY[veh_type]

        # --- Service history -----------------------------------------------
        # End-of-life vehicles cluster around 12-16 years in service, with a
        # long tail of early write-offs (accident damage) and late survivors.
        service_years = float(np.clip(rng.gamma(shape=7.0, scale=2.0), 1.0, 32.0))
        mfg_year = int(reference_year - round(service_years))
        odometer_km = float(np.clip(
            duty["annual_km"] * service_years * rng.lognormal(0.0, 0.35),
            1000.0, 600000.0))

        # --- Mass from geometry and density --------------------------------
        # TYPICAL_MASS_KG is quoted for each component's PRIMARY material, which
        # is the first entry in its COMPONENT_MATERIALS list. Substituting a
        # denser or lighter material rescales the part mass from there. Taking
        # the mean density of all candidates instead would distort components
        # whose candidate list mixes metals and polymers, e.g. a tyre.
        baseline_density = mp.material(choices[0])["density_kg_m3"]
        # Designers partly compensate thickness for density, so mass scales
        # sub-linearly with the density ratio, and the ratio is bounded to keep
        # substituted variants within a credible design envelope.
        density_ratio = np.clip(
            (mat["density_kg_m3"] / baseline_density) ** 0.55, 0.55, 2.10)
        mass_kg = float(mp.TYPICAL_MASS_KG[comp_name] * density_ratio
                        * rng.lognormal(0.0, 0.22))
        mass_kg = float(np.clip(mass_kg, 0.3, 300.0))

        # --- Construction attributes ---------------------------------------
        if mat["family"] in ("Ferrous metal", "Non-ferrous metal"):
            joint_opts, joint_p = ["Welded", "Bolted", "Adhesive-bonded"], [0.55, 0.35, 0.10]
        elif mat["family"] == "Composite":
            joint_opts, joint_p = ["Adhesive-bonded", "Bolted", "Over-moulded"], [0.60, 0.25, 0.15]
        elif mat["family"] == "Elastomer":
            joint_opts, joint_p = ["Over-moulded", "Clip-fit", "Bolted"], [0.50, 0.30, 0.20]
        elif mat["family"] == "Ceramic / glass":
            joint_opts, joint_p = ["Adhesive-bonded", "Clip-fit"], [0.85, 0.15]
        else:
            joint_opts, joint_p = ["Clip-fit", "Bolted", "Over-moulded", "Adhesive-bonded"], [0.45, 0.25, 0.20, 0.10]
        joining_method = str(rng.choice(joint_opts, p=joint_p))

        coat_prob = 0.75 if comp_name in ("Body Panel", "Bumper") else 0.25
        if mat["family"] == "Ceramic / glass":
            coat_prob = 0.05
        coating_present = bool(rng.random() < coat_prob)

        legacy_additive = bool(
            mfg_year < ELV_ANNEX_II_CUTOFF_YEAR
            and mat["family"] in ("Thermoplastic", "Thermoset", "Elastomer")
            and rng.random() < 0.65
        )

        # --- Latent lifecycle state ----------------------------------------
        degradation_index = _degradation_index(
            mat, comp, duty, service_years, odometer_km, rng)

        # Contamination grows with exposure to fluids over the service life.
        contamination_level = float(np.clip(
            comp["contamination_risk"] * (0.45 + 0.55 * np.sqrt(service_years / 20.0))
            * rng.lognormal(0.0, 0.30),
            0.0, 1.0))

        separability = _separability(comp, joining_method, coating_present)

        hazard_score = float(np.clip(
            mat["toxicity_class"] / 3.0
            + (0.18 if legacy_additive else 0.0)
            + 0.12 * contamination_level,
            0.0, 1.0))

        # Residual mechanical capability. Ageing attacks strength, but only
        # partially, so strength is an incomplete window onto degradation.
        virgin_strength = float(mat["tensile_strength"] * rng.lognormal(0.0, 0.06))
        strength_retention = float(np.clip(
            1.0 - 0.62 * degradation_index - 0.08 * contamination_level, 0.05, 1.0))
        true_residual_strength = virgin_strength * strength_retention
        # Non-destructive testing has real measurement error.
        measured_strength = float(true_residual_strength * rng.lognormal(0.0, 0.08))

        state = dict(
            degradation_index=degradation_index,
            contamination_level=contamination_level,
            separability=separability,
            hazard_score=hazard_score,
            strength_retention=strength_retention,
            coating_present=coating_present,
            legacy_additive=legacy_additive,
        )

        # --- Label draw ----------------------------------------------------
        # The calibration offsets are folded in here so that `scores` is the
        # exact utility vector the label is drawn from. The Bayes-ceiling
        # estimate relies on that: an oracle must be scored against the same
        # utilities the generator used, not the pre-calibration ones.
        base_scores = _mcda_scores(mat, comp, state) + DISPOSITION_BIAS
        # Per-part shocks from factors no database records (see
        # UNOBSERVED_SIGMA). Never exported, so no model can recover them.
        unobserved = rng.normal(0.0, UNOBSERVED_SIGMA)
        scores = base_scores + unobserved
        # Gumbel noise over the utilities gives a softmax choice model: the
        # highest-scoring option usually wins, but near-ties genuinely flip.
        noisy = scores * LABEL_TEMPERATURE + rng.gumbel(0.0, 1.0, size=3)
        disposition = DISPOSITIONS[int(np.argmax(noisy))]

        risk_tier, risk_score = _environmental_risk(mat, state, mass_kg, rng)

        # --- Observable engineered features --------------------------------
        family = mat["family"]
        reproc_fraction = mp.REPROCESSING_ENERGY_FRACTION[family]

        embodied_energy_mj = mass_kg * mat["embodied_energy"]
        carbon_footprint = mass_kg * mat["gwp_kg_co2e_per_kg"]
        # CO2 avoided by recycling = virgin burden displaced minus reprocessing
        # burden incurred, less the landfill burden that is also avoided.
        co2_avoided = (carbon_footprint * (1.0 - reproc_fraction)
                       - mass_kg * mp.LANDFILL_CO2_PER_KG)

        # Expected process yield if this part is sent to recycling. Observable
        # from plant records, and a partial reflection of separability.
        recycling_efficiency = float(np.clip(
            100.0 * mat["recycle_fraction"]
            * (0.55 + 0.45 * separability)
            * (1.0 - 0.30 * contamination_level)
            * rng.lognormal(0.0, 0.10),
            1.0, 99.0))

        # Both economic figures carry genuine market and operational noise.
        # That noise is not cosmetic: without it, `Recyclate Value ($)` would be
        # an exactly invertible function of the hidden contamination level, and
        # `Dismantling Cost ($)` of the hidden separability, which would hand
        # the model the latent state it is supposed to have to infer. The scatter
        # is physically real - scrap prices move with grading and market, and
        # labour time varies by operator skill and yard layout.
        recyclate_value = (mass_kg * mat["recyclate_value"]
                           * (1.0 - 0.35 * contamination_level)
                           * rng.lognormal(0.0, 0.15))
        # Labour to remove and separate the part, at an indicative USD 22/hour.
        dismantling_cost = (22.0 * (0.12 + 0.85 * (1.0 - separability))
                            * (1.0 + 0.4 * np.log1p(mass_kg) / np.log1p(60.0))
                            * rng.lognormal(0.0, 0.18))

        hazard_level = ("Low" if hazard_score < 0.28 else
                        "Medium" if hazard_score < 0.58 else "High")

        # Surface inspection grade: 1 = pristine, 5 = severely degraded. Driven
        # by the UV and corrosion channels, so it is a different partial view of
        # degradation than the strength measurement is.
        surface_driver = np.clip(
            0.6 * degradation_index
            + 0.4 * (mat["uv_degradation"] * comp["uv_load"]) * min(service_years / 15.0, 1.0)
            + rng.normal(0.0, 0.07), 0.0, 1.0)
        surface_grade = int(np.clip(1 + np.floor(surface_driver * 5.0), 1, 5))

        row = {
            # --- identity / categorical ---
            "Material Name": mat_name,
            "Material Family": family,
            "Component": comp_name,
            "Vehicle Type": veh_type,
            "Joining Method": joining_method,
            # --- service history ---
            "Manufacturing Year": mfg_year,
            "Service Life (years)": round(service_years, 2),
            "Odometer (km)": round(odometer_km, 0),
            # --- physical ---
            "Part Mass (kg)": round(mass_kg, 3),
            "Density (kg/m3)": mat["density_kg_m3"],
            "Virgin Tensile Strength (MPa)": round(virgin_strength, 2),
            "Measured Tensile Strength (MPa)": round(measured_strength, 2),
            "Max Service Temp (C)": mat["max_service_temp"],
            # --- environmental ---
            "Embodied Energy (MJ)": round(embodied_energy_mj, 2),
            "Carbon Footprint (kg CO2eq)": round(carbon_footprint, 3),
            "CO2 Avoided if Recycled (kg)": round(co2_avoided, 3),
            "Recycling Efficiency (%)": round(recycling_efficiency, 2),
            "Recycled Content (%)": round(float(np.clip(
                100.0 * mat["recycle_fraction"] * rng.uniform(0.15, 0.75), 0.0, 95.0)), 2),
            # --- condition observations (coarse/noisy views of latent state) ---
            "Material Condition": _condition_label(degradation_index),
            "Surface Degradation Grade": surface_grade,
            "Fluid Contamination": "Yes" if contamination_level > 0.5 else "No",
            "Coating Present": "Yes" if coating_present else "No",
            # --- hazard / policy ---
            "Hazardous Level": hazard_level,
            "Legacy Additive (pre-ELV)": "Yes" if legacy_additive else "No",
            "Safety Critical": "Yes" if comp["safety_critical"] else "No",
            "Reprocessable": "Yes" if mat["reprocessable"] else "No",
            # --- economics ---
            "Recyclate Value ($)": round(recyclate_value, 2),
            "Dismantling Cost ($)": round(dismantling_cost, 2),
            # --- targets ---
            "Disposition": disposition,
            "Environmental Risk": risk_tier,
        }

        if include_latents:
            # Marginalise over the unobserved shocks and the Gumbel noise, with
            # every observable-determining quantity held fixed. The resulting
            # distribution is what the BEST POSSIBLE feature-based model could
            # output for this part, so its maximum is that model's per-part
            # accuracy ceiling. Averaged over parts by
            # `estimate_feature_ceiling`.
            draws = (base_scores + rng.normal(0.0, UNOBSERVED_SIGMA,
                                              size=(_MC_DRAWS, 3))
                     ) * LABEL_TEMPERATURE \
                + rng.gumbel(0.0, 1.0, size=(_MC_DRAWS, 3))
            counts = np.bincount(draws.argmax(axis=1), minlength=3) / _MC_DRAWS
            row.update({
                "_p_reuse": round(float(counts[0]), 4),
                "_p_recycle": round(float(counts[1]), 4),
                "_p_dispose": round(float(counts[2]), 4),
                "_max_achievable_p": round(float(counts.max()), 4),
            })
            row.update({
                "_latent_degradation": round(degradation_index, 4),
                "_latent_contamination": round(contamination_level, 4),
                "_latent_separability": round(separability, 4),
                "_latent_hazard": round(hazard_score, 4),
                "_latent_strength_retention": round(strength_retention, 4),
                "_score_reuse": round(scores[0], 4),
                "_score_recycle": round(scores[1], 4),
                "_score_dispose": round(scores[2], 4),
                "_risk_score": round(risk_score, 4),
            })

        rows.append(row)

    return pd.DataFrame(rows)


def inject_realistic_missingness(df, rate=0.04, seed=RNG_SEED):
    """
    Blank out a small fraction of values in the fields a real dismantling yard
    most often fails to record, so that the preprocessing stage has genuine
    missing data to handle (Objective 1) rather than a synthetically perfect table.
    """
    rng = np.random.default_rng(seed + 1)
    out = df.copy()
    prone = ["Measured Tensile Strength (MPa)", "Odometer (km)",
             "Recycling Efficiency (%)", "Recycled Content (%)",
             "Surface Degradation Grade", "Recyclate Value ($)"]
    for col in prone:
        if col in out.columns:
            mask = rng.random(len(out)) < rate
            out.loc[mask, col] = np.nan
    return out


def estimate_bayes_ceiling(n_samples=40000, seed=RNG_SEED):
    """
    Estimate the irreducible error of the label-generating process.

    Because labels are drawn through Gumbel noise over the MCDA utilities, even
    an oracle with perfect knowledge of the latent state cannot predict every
    label. The accuracy of always choosing the highest-utility option is
    therefore the theoretical ceiling for ANY model, and the honest reference
    point against which the trained models should be judged.
    """
    df = generate(n_samples=n_samples, seed=seed, include_latents=True)
    scores = df[["_score_reuse", "_score_recycle", "_score_dispose"]].to_numpy()
    oracle = np.array(DISPOSITIONS)[scores.argmax(axis=1)]
    return float((oracle == df["Disposition"].to_numpy()).mean())


def calibrate_bias(target=(0.20, 0.50, 0.30), n_samples=4000, seed=7,
                   iterations=60, tol=0.008):
    """
    Refit `DISPOSITION_BIAS` so the generated class mix matches a target
    composition, by coordinate descent on the realised proportions.

    The default target follows the EU ELV Directive composition: roughly 20%
    reuse, 50% recycling and 30% disposal by part count. Re-run this if the
    MCDA weights are ever changed, then write the result back into the module
    constant so generation stays deterministic.
    """
    global DISPOSITION_BIAS
    target = np.asarray(target, dtype=float)
    bias = np.zeros(3)
    history = []
    for _ in range(iterations):
        DISPOSITION_BIAS = bias
        df = generate(n_samples=n_samples, seed=seed)
        mix = (df["Disposition"].value_counts(normalize=True)
               .reindex(DISPOSITIONS).fillna(0.0).to_numpy())
        history.append(mix)
        error = target - mix
        if np.abs(error).max() < tol:
            break
        bias = bias + 0.55 * error / target
        bias = bias - bias.mean()   # offsets matter only up to a constant
    return bias, history[-1]


def estimate_feature_ceiling(n_samples=6000, seed=RNG_SEED):
    """
    Estimate the accuracy ceiling for a model that sees only exported features.

    This is the number trained models should actually be judged against.
    `estimate_bayes_ceiling` assumes an oracle that knows the unobserved shocks
    too, so it is a loose upper bound; this function marginalises those shocks
    out, holding every observable-determining quantity fixed, and averages the
    largest attainable class probability over parts.

    It remains mildly optimistic, because it credits the model with perfect
    knowledge of the latent state behind the noisy exported observations (the
    coarse condition grade, the 8% NDT strength error). A well-trained model
    landing a few points below this value is therefore performing as well as the
    data permits, and the remaining gap is irreducible - not a tuning failure.
    """
    df = generate(n_samples=n_samples, seed=seed, include_latents=True)
    return float(df["_max_achievable_p"].mean())
