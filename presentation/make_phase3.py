def esc(text):
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def fill_body(slide, blocks, head_size=1700, bullet_size=1400):
    """
    Replace the 'Body Text' frame with `blocks`.

    Each block is ('head' | 'bullet' | 'sub' | 'key', text). 'key' renders a
    bullet in navy bold, used to make the handful of headline numbers stand out
    without resorting to a different layout.
    """
    body = shape_by_name(slide, "Body Text")
    if body is None:
        raise ValueError("slide has no 'Body Text' shape")

    txBody = body.text_frame._txBody
    for para in txBody.findall(f"{NS}p"):
        txBody.remove(para)

    first = True
    for kind, text in blocks:
        if kind == "head":
            xml = P_HEAD.format(text=esc(text), size=head_size,
                                before=0 if first else 600)
        elif kind == "key":
            xml = P_BULLET.format(
                text=esc(text), size=bullet_size, marl=342900, glyph="•",
                bold=1, fill='<a:solidFill><a:srgbClr val="002060"/></a:solidFill>')
        elif kind == "sub":
            xml = P_BULLET.format(
                text=esc(text), size=bullet_size - 100, marl=742950, glyph="–",
                bold=0, fill="")
        else:
            xml = P_BULLET.format(
                text=esc(text), size=bullet_size, marl=342900, glyph="•",
                bold=0, fill="")
        txBody.append(etree.fromstring(xml))
        first = False
    return body


def fill_flow(slide, steps):
    """
    Fill the methodology flow chart: each rounded rectangle holds a bold blue
    step name on the first line and a plain description on the second.
    """
    boxes = [s for s in slide.shapes if s.name.startswith("Rounded Rectangle")]
    for box, (name, detail) in zip(boxes, steps):
        paras = box.text_frame.paragraphs
        if paras[0].runs:
            paras[0].runs[0].text = name
            for extra in paras[0].runs[1:]:
                extra.text = ""
        if len(paras) > 1 and paras[1].runs:
            paras[1].runs[0].text = detail
            for extra in paras[1].runs[1:]:
                extra.text = ""
    return len(boxes)


def add_fitted_picture(slide, path, left, top, width, height):
    """Place an image inside a box, preserving its aspect ratio and centring it."""
    with Image.open(path) as im:
        img_w, img_h = im.size
    scale = min(width / img_w, height / img_h)
    w, h = img_w * scale, img_h * scale
    return slide.shapes.add_picture(
        path, Inches(left + (width - w) / 2), Inches(top + (height - h) / 2),
        Inches(w), Inches(h))


def add_caption(slide, text, left, top, width):
    box = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width),
                                   Inches(0.24))
    tf = box.text_frame
    tf.word_wrap = True
    para = tf.paragraphs[0]
    run = para.add_run()
    run.text = text
    run.font.size = Pt(10)
    run.font.name = "Calibri"
    run.font.italic = True
    from pptx.dml.color import RGBColor
    run.font.color.rgb = RGBColor(0x40, 0x40, 0x40)
    from pptx.enum.text import PP_ALIGN
    para.alignment = PP_ALIGN.CENTER
    return box


