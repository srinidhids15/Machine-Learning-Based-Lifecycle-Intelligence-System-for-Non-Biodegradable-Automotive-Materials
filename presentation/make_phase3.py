def clone_slide(prs, src, drop_pictures=False):
    """
    Append a copy of `src` to `prs`, preserving its exact shape formatting.

    Pictures are dropped on request because a deep-copied <p:pic> still points
    at a relationship ID that exists only in the source slide; picture slides
    are therefore rebuilt with fresh images via `add_fitted_picture`.
    """
    new = prs.slides.add_slide(src.slide_layout)
    for shape in list(new.shapes):          # clear the layout's placeholders
        shape._element.getparent().remove(shape._element)
    for shape in src.shapes:
        if drop_pictures and shape.shape_type == MSO_SHAPE_TYPE.PICTURE:
            continue
        new.shapes._spTree.append(copy.deepcopy(shape._element))
    return new


def shape_by_name(slide, name):
    for shape in slide.shapes:
        if shape.name == name:
            return shape
    return None


def set_title(slide, text):
    """The title bar is the full-width text box at the top of every slide."""
    for shape in slide.shapes:
        if not getattr(shape, "has_text_frame", False):
            continue
        if Emu(shape.width).inches > 9.5 and Emu(shape.top).inches < 0.2:
            para = shape.text_frame.paragraphs[0]
            if para.runs:
                para.runs[0].text = text
                for extra in para.runs[1:]:
                    extra.text = ""
            return shape
    return None


